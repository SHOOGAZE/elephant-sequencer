"""Sound bank: every sound renders finite and audible, picking one assigns a slot once, the sheet has the BANK tab."""
from common import *
r=Run()
n=r.ev("GR.bank.reduce((a,x)=>a+x.names.length,0)")
check('bank has 50+ sounds',n>=50,n)
bad=r.ev("""()=>{const o=[];GR.Samples.slots.length=0;for(const x of GR.bank)for(const nm of x.names){GR.Samples.slots.length=0;const i=GR.bankSlot(nm),c=GR.Samples.slots[i].ch[0];let m=0,b=0;for(let k=0;k<c.length;k++){const v=c[k];if(!isFinite(v))b++;m=Math.max(m,Math.abs(v))}if(b||m<.3||m>1.01)o.push(nm)}return o}""")
check('all bank sounds finite and audible',not bad,bad)
a=r.ev("GR.bankSlot('REESE')");b=r.ev("GR.bankSlot('REESE')")
check('picking twice reuses the slot',a==b,(a,b))
r.ev("GR.Samples.slots.length=0;GR.proj=GR.defaultProject()");r.go('seq');r.ev("GRUI.renderTab()")
r.pg.click('.thead button:has-text("SOUND")');r.pg.wait_for_timeout(300)
check('sheet opens on BANK when the pool is empty',r.ev("document.querySelector('.psheet .cats .chip.on').textContent")=='BANK')
check('role chips shown',r.ev("document.querySelectorAll('.bankroles .chip').length")==8)
r.pg.click('.bankroles .chip:has-text("BASS")');r.pg.wait_for_timeout(200)
r.pg.click('.sgrid .sitem:has-text("ACID")');r.pg.wait_for_timeout(400)
check('picked sound lands on the track',r.ev("GR.Samples.slots[GR.proj.tracks[GRUI.U.tr].slot].name")=='ACID')
r.close();done()
