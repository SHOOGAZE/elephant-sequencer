"""Sequencer: toggling steps, undo, pattern copy, track length, P-locks."""
from common import *
r=Run()
r.ev("GRUI.go('seq')");r.pg.wait_for_timeout(300)
r.ev("GR.proj=GR.defaultProject();GRUI.renderTab()");r.pg.wait_for_timeout(200)
cells=r.pg.locator('#s-seq .gc')
check('16 trig keys',cells.count()==16,cells.count())
check('16 track keys',r.pg.locator('#s-seq .tk').count()==16)
cells.nth(0).click();r.pg.wait_for_timeout(150)
check('step toggles on',r.ev("GR.proj.patterns[0][0][0].on")==1)
cells.nth(0).click();r.pg.wait_for_timeout(150)
check('step toggles off',r.ev("GR.proj.patterns[0][0][0].on")==0)
r.ev("GR.proj.patterns[0][1][4].on=1;GR.proj.patterns[0][1][4].lock={8:.3}")
check('p-lock survives serialize',r.ev("GR.revive(JSON.parse(JSON.stringify(GR.serialize(GR.proj)))).patterns[0][1][4].lock[8]")==0.3)
r.ev("GR.proj.tracks[2].len=12")
check('track length kept',r.ev("GR.revive(JSON.parse(JSON.stringify(GR.serialize(GR.proj)))).tracks[2].len")==12)
r.ev("""()=>{GR.proj=GR.defaultProject();const n=44100,a=new Float32Array(n);for(let i=0;i<n;i++)a[i]=Math.sin(6.2832*180*i/44100)*Math.exp(-i/2500);const k=GR.Samples.add('T',[a],44100,true);GR.proj.tracks.forEach(t=>t.slot=k)}""")
cnt=r.ev("""async()=>{const P=GR.proj;const run=async n=>{P.patterns[0].forEach(r=>r.forEach(s=>{s.on=0}));const s=P.patterns[0][0][0];s.on=1;s.vel=1;s.rtg=n;const b=await GR.renderOffline({bars:1,tail:.2});const L=b.getChannelData(0);let e=0;const w=Math.floor(44100*.01);for(let i=0;i<L.length-w;i+=w){let m=0;for(let j=0;j<w;j++)m=Math.max(m,Math.abs(L[i+j]));if(m>.05)e++}return e};return [await run(1),await run(4)]}""")
check('retrig adds more hits',cnt[1]>cnt[0],cnt)
r.close();done()
